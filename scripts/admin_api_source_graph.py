"""Exact private Admin API import closure for its independently built image.

The graph is generated by source-only AST traversal. It never executes
application modules or connects to a database or an external service.
"""

from __future__ import annotations

import ast
import importlib.util
from pathlib import Path


def _imports(path: Path, package: str, known: set[str]) -> set[str]:
    selected: set[str] = set()

    class Collector(ast.NodeVisitor):
        def visit_If(self, node: ast.If) -> None:
            if isinstance(node.test, ast.Name) and node.test.id == "TYPE_CHECKING":
                for item in node.orelse:
                    self.visit(item)
            else:
                self.generic_visit(node)

        def visit_Import(self, node: ast.Import) -> None:
            selected.update(alias.name for alias in node.names if alias.name in known)

        def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
            base = (
                importlib.util.resolve_name("." * node.level + (node.module or ""), package)
                if node.level
                else node.module or ""
            )
            if base not in known and base.split(".", 1)[0] in {"common", "presentation"}:
                raise ValueError(f"missing private Admin source import {base} in {path}")
            if base in known:
                selected.add(base)
            selected.update(
                f"{base}.{alias.name}" for alias in node.names if f"{base}.{alias.name}" in known
            )

    Collector().visit(ast.parse(path.read_text(encoding="utf-8"), filename=str(path)))
    return selected


def private_admin_files(root: Path) -> dict[str, str]:
    common_root = root / "services/common"
    admin_root = root / "services/admin-api/src"
    known: dict[str, tuple[Path, str]] = {}
    for folder, module_root in ((common_root, root / "services"), (admin_root, admin_root)):
        for path in sorted(folder.rglob("*.py")):
            if path.is_symlink() or not path.is_file():
                raise ValueError("unsafe Admin source file")
            segments = path.relative_to(module_root).with_suffix("").parts
            module = ".".join(segments[:-1] if segments[-1] == "__init__" else segments)
            if module in known:
                raise ValueError(f"duplicate Admin module {module}")
            if path.name == "__init__.py":
                target = "/".join(segments[:-1]) + "/__init__.py"
            else:
                target = "/".join(segments) + ".py"
            known[module] = (path, target)

    selected: set[str] = set()
    pending = ["platform_runtime", "presentation.private_c2_api"]
    while pending:
        module = pending.pop()
        if module in selected:
            continue
        if module not in known:
            raise ValueError(f"Admin private runtime depends on absent module {module}")
        selected.add(module)
        path, _target = known[module]
        package = module if path.name == "__init__.py" else module.rpartition(".")[0]
        pending.extend(_imports(path, package, set(known)) - selected)
        for index in range(1, len(module.split("."))):
            parent = ".".join(module.split(".")[:index])
            if parent in known:
                pending.append(parent)

    return {
        known[module][0].relative_to(root).as_posix(): known[module][1]
        for module in sorted(selected)
    }
